// Scans the workspace for AGENTS.md, CLAUDE.md, or .ollamaforge.md files at
// the root and up to 2 directory levels deep. Content is injected into the
// system prompt so the model has per-directory conventions without manual ingestion.
//
// File priority (highest wins on conflict): .ollamaforge.md > AGENTS.md > CLAUDE.md
// Only files â‰¤ 8000 chars are included to prevent context bloat.
//
// ARCHITECTURE.md is also loaded from the workspace root (root only, not subdirs)
// as a separate always-present section -- it's auto-generated by the code indexer.
export const CONTEXT_FILE_NAMES = ['.ollamaforge.md', 'AGENTS.md', 'CLAUDE.md'];
export const MAX_CONTEXT_FILE_BYTES = 8000;

export async function loadHierarchicalContext(workspaceRoot: string): Promise<string> {
    const sections: string[] = [];
    try {
        // â"€â"€ .ollamaforge/context.md (highest priority -- strategic project/engagement context) â"€â"€
        // This is the intentional home for persistent, session-spanning agent context:
        // project goals, constraints, rules of engagement, team conventions, environment facts.
        // Loaded before everything else so it frames all subsequent context.
        const agentContextPath = path.join(workspaceRoot, '.ollamaforge', 'context.md');
        try {
            const stat = fs.statSync(agentContextPath);
            if (stat.isFile()) {
                const content = fs.readFileSync(agentContextPath, 'utf8').slice(0, 32_000);
                sections.push(`### .ollamaforge/context.md (project context -- always apply)\n${content.trim()}`);
                logInfo(`[context-files] Loaded .ollamaforge/context.md (${content.length} chars)`);
            }
        } catch { /* file doesn't exist yet -- skip */ }

        // â"€â"€ .ollamaforge/feedback.md (self-improvement: past response issues flagged by user) â"€â"€
        // Loaded early so the agent sees its own failure patterns before generating responses.
        // Each entry is a labeled example of what went wrong -- agent should avoid repeating them.
        const feedbackPath = path.join(workspaceRoot, '.ollamaforge', 'feedback.md');
        try {
            const stat = fs.statSync(feedbackPath);
            if (stat.isFile()) {
                const content = fs.readFileSync(feedbackPath, 'utf8').slice(0, 8_000);
                sections.push(`### .ollamaforge/feedback.md (past response issues -- avoid repeating these)\nThe following are behaviors the user has flagged as problems in previous responses. Study them and do NOT repeat these patterns:\n${content.trim()}`);
                logInfo(`[context-files] Loaded feedback.md (${content.length} chars)`);
            }
        } catch { /* file doesn't exist yet -- skip */ }

        // â"€â"€ ARCHITECTURE.md (root only, loaded first as project structure reference) â"€â"€
        const archPath = path.join(workspaceRoot, 'ARCHITECTURE.md');
        try {
            const stat = fs.statSync(archPath);
            if (stat.isFile()) {
                const content = fs.readFileSync(archPath, 'utf8').slice(0, MAX_CONTEXT_FILE_BYTES);
                sections.push(`### ARCHITECTURE.md (auto-generated project structure)\n${content.trim()}`);
                logInfo(`[context-files] Loaded ARCHITECTURE.md (${content.length} chars)`);
            }
        } catch { /* file doesn't exist yet -- skip */ }

        // â"€â"€ DEPLOYMENT.md (root only -- SSH users, scp patterns, service names) â"€â"€
        const deployPath = path.join(workspaceRoot, 'DEPLOYMENT.md');
        try {
            const stat = fs.statSync(deployPath);
            if (stat.isFile()) {
                const content = fs.readFileSync(deployPath, 'utf8').slice(0, MAX_CONTEXT_FILE_BYTES);
                sections.push(`### DEPLOYMENT.md (SSH users, deploy commands, service names -- always check before forming ssh/scp commands)\n${content.trim()}`);
                logInfo(`[context-files] Loaded DEPLOYMENT.md (${content.length} chars)`);
            }
        } catch { /* file doesn't exist -- skip */ }

        // â"€â"€ PLAN.md (root only, loaded second -- development plan and backlog) â"€â"€
        const planPath = path.join(workspaceRoot, 'PLAN.md');
        try {
            const stat = fs.statSync(planPath);
            if (stat.isFile()) {
                const content = fs.readFileSync(planPath, 'utf8').slice(0, MAX_CONTEXT_FILE_BYTES);
                sections.push(`### PLAN.md (development plan and backlog)\n${content.trim()}`);
                logInfo(`[context-files] Loaded PLAN.md (${content.length} chars)`);
            }
        } catch { /* file doesn't exist -- skip */ }

        // â"€â"€ Convention/guide files: root + immediate subdirectories â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€
        const candidates: string[] = [workspaceRoot];
        try {
            const entries = fs.readdirSync(workspaceRoot, { withFileTypes: true });
            for (const e of entries) {
                if (!e.isDirectory()) { continue; }
                if (SKIP_DIRS.has(e.name) || e.name.startsWith('.')) { continue; }
                candidates.push(path.join(workspaceRoot, e.name));
            }
        } catch { /* can't list root -- just use root */ }

        const seen = new Set<string>(); // deduplicate by canonical path
        for (const dir of candidates) {
            for (const fname of CONTEXT_FILE_NAMES) {
                const fpath = path.join(dir, fname);
                if (seen.has(fpath)) { continue; }
                try {
                    const stat = fs.statSync(fpath);
                    if (!stat.isFile()) { continue; }
                    const content = fs.readFileSync(fpath, 'utf8').slice(0, MAX_CONTEXT_FILE_BYTES);
                    const rel = path.relative(workspaceRoot, fpath).replace(/\\/g, '/');
                    sections.push(`### ${rel}\n${content.trim()}`);
                    seen.add(fpath);
                    logInfo(`[context-files] Loaded ${rel} (${content.length} chars)`);
                    break; // highest-priority file wins for this directory
                } catch { /* file doesn't exist or can't be read -- skip */ }
            }
        }
    } catch { /* never let context scanning break agent startup */ }

    // â"€â"€ Pending proposed rules reminder â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€â"€
    // If the dream agent has written proposed_rules.md with unaccepted rules,
    // inject a one-line reminder so the agent mentions it to the user naturally.
    try {
        const proposedPath = path.join(workspaceRoot, '.ollamaforge', 'proposed_rules.md');
        const stat = fs.statSync(proposedPath);
        if (stat.isFile()) {
            const content = fs.readFileSync(proposedPath, 'utf8');
            const ruleCount = (content.match(/^## Rule:/gm) || []).length;
            if (ruleCount > 0) {
                sections.push(`### Pending: proposed behavioral rules\nThe dream agent has proposed ${ruleCount} new rule${ruleCount === 1 ? '' : 's'} based on past feedback. Remind the user once per session: "You have ${ruleCount} proposed rule${ruleCount === 1 ? '' : 's'} ready to review -- run \`Ollama Forge: Accept Proposed Rules\` from the command palette to apply them."`);
                logInfo(`[context-files] Found ${ruleCount} pending proposed rule(s)`);
            }
        }
    } catch { /* no proposed_rules.md -- skip */ }

    if (sections.length === 0) { return ''; }
    return `## Project Context Files\nThe following files define project conventions, architecture, and guidelines:\n\n${sections.join('\n\n')}`;
}

/** Snapshot the mtime (ms) of each context file currently on disk. */
export function snapshotContextFileMtimes(workspaceRoot: string): Map<string, number> {
    const result = new Map<string, number>();
    const roots = [workspaceRoot];
    try {
        const entries = fs.readdirSync(workspaceRoot, { withFileTypes: true });
        for (const e of entries) {
            if (e.isDirectory() && !SKIP_DIRS.has(e.name) && !e.name.startsWith('.')) {
                roots.push(path.join(workspaceRoot, e.name));
            }
        }
    } catch { /* ignore */ }
    // Also check .ollamaforge/context.md
    const specialFiles = [
        path.join(workspaceRoot, '.ollamaforge', 'context.md'),
        path.join(workspaceRoot, 'ARCHITECTURE.md'),
        path.join(workspaceRoot, 'PLAN.md'),
    ];
    for (const fpath of specialFiles) {
        try { result.set(fpath, fs.statSync(fpath).mtimeMs); } catch { /* skip */ }
    }
    for (const dir of roots) {
        for (const fname of CONTEXT_FILE_NAMES) {
            const fpath = path.join(dir, fname);
            try { result.set(fpath, fs.statSync(fpath).mtimeMs); } catch { /* skip */ }
        }
    }
    return result;
}

export async function buildSystemPromptAsync(autoSaveMemory: boolean, workspaceRoot?: string): Promise<string> {
    const [guidance, hierarchicalCtx] = await Promise.all([
        workspaceRoot ? buildProjectTypeGuidanceAsync(workspaceRoot) : Promise.resolve(''),
        workspaceRoot ? loadHierarchicalContext(workspaceRoot) : Promise.resolve(''),
    ]);
    return buildSystemPrompt(autoSaveMemory, workspaceRoot, guidance, hierarchicalCtx);
}
